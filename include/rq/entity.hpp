           SIF::LAZY_DECLARATION | SIF::INTERFACE_IMPLEMENTATION |
           SIF::IS_RUNTIME_TYPE | SIF::IS_COMTIME_TYPE | SIF::IS_OBJECT_SCOPE;
  case S::ADAPTER_SPECIALIZATION:
