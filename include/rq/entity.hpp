    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::EAGER_DECLARATION;
  case S::ELSE_STATEMENT:
    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::EAGER_DECLARATION;
  case S::SWITCH_STATEMENT:
    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::EAGER_DECLARATION;
  case S::CASE_STATEMENT:
