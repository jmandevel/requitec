           SIF::LAZY_DECLARATION | SIF::ALIAS_IMPLEMENTATION;
  case S::CONCEPT_SPECIALIZATION:
    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::NAMED_TABLE |
           SIF::LAZY_DECLARATION | SIF::CONCEPT_IMPLEMENTATION;
  case S::VARIANT_SPECIALIZATION:
    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::NAMED_TABLE |
           SIF::LAZY_DECLARATION | SIF::VARIANT_IMPLEMENTATION;

  // TEMPLATES
  case S::CLASS_TEMPLATE:
    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::NAMED_TABLE |
           SIF::LAZY_DECLARATION | SIF::TEMPLATE;
  case S::ENUM_TEMPLATE:
    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::NAMED_TABLE |
           SIF::LAZY_DECLARATION | SIF::TEMPLATE;
  case S::INTERFACE_TEMPLATE:
    return SIF::TABLE_MEMBER | SIF::SYMBOL_TABLE | SIF::NAMED_TABLE |
           SIF::LAZY_DECLARATION | SIF::TEMPLATE;
  case S::ADAPTER_TEMPLATE:
